/* ESET SOC Lite — Japanese / English UI toggle
 *
 * Loaded first (before dashboard-viz.js and dashboard.js), since both depend on
 * t()/tBadge()/applyStaticI18n() being available at their own load time.
 *
 * Scope: this translates dashboard UI CHROME — navigation, headers, labels,
 * buttons, table columns, empty-states, and the small fixed vocabulary of status
 * badges. It deliberately does NOT translate:
 *   - the Emails section (#view-emails) or anything triggered from it — left
 *     exactly as-is, per product requirement.
 *   - AI-generated notification content (client_notification_ja.summary etc.) —
 *     that is real bilingual data produced by the AI provider, not dashboard chrome.
 *   - raw application log lines — structured audit data, not localizable text.
 *   - free-text backend-authored prose in AI Visibility (decision-summary values,
 *     timeline event detail text, data-category "origin" sentences) — these are
 *     diagnostic/audit content generated by the Python backend, the same category
 *     of thing as log lines, not fixed dashboard vocabulary.
 * Japanese is the default for a visitor who has never chosen; after that the
 * choice is remembered in localStorage (the same store theme.js uses), so a
 * refresh — or reopening the app tomorrow — keeps the language the operator
 * actually works in instead of resetting to Japanese every time.
 */
"use strict";

const LANG_STORAGE_KEY = "soc_lite_lang";

/** The stored choice, or Japanese when there is none (or storage is unavailable,
 * e.g. a private window — the dashboard must still load). */
function storedLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === "ja" || saved === "en") return saved;
  } catch (e) { /* storage blocked — fall through to the default */ }
  return "ja";
}

