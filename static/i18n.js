/** Looks up a translation key in the current language, falling back to English,
 * then to the key itself so a missing entry never shows blank. `args` are passed
 * through when the entry is a function (for interpolated strings). */
function t(key, ...args) {
  const table = I18N[state_lang.current] || I18N.en;
  const entry = table[key] !== undefined ? table[key] : I18N.en[key];
  if (entry === undefined) return key;
  return typeof entry === "function" ? entry(...args) : entry;
}

