/**
 * Translates backend-authored English prose (AI Visibility diagnostics, pipeline
 * stage details, risk rationale, a few API error messages) into natural Japanese
 * where the exact source text is known. See the block comment above for the
 * matching strategy and why an unmatched string is returned unchanged rather than
 * guessed at. In English mode this is always the identity function.
 */
function tBackendText(text) {
  if (state_lang.current !== "ja" || !text) return text;
  if (BACKEND_TEXT_JA[text] !== undefined) return BACKEND_TEXT_JA[text];
  for (const [re, fn] of BACKEND_TEXT_TEMPLATES) {
    const m = text.match(re);
    if (m) return fn(m);
  }
  return text;
}

