/** Translates every static [data-i18n]/[data-i18n-placeholder] element in the
 * document. Elements inside #view-emails are never given these attributes in the
 * first place, so this naturally never touches the Emails section. */
function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
  applyMixedContentI18n();
}

/** A handful of strings mix translatable prose with an embedded technical
 * <span class="mono">...</span> (an API path, a header name) that must never be
 * touched. Handled separately from [data-i18n] since setting .textContent on
 * their container would destroy the embedded markup. */
function applyMixedContentI18n() {
  const alertsEmpty = document.getElementById("alertsEmpty");
  if (alertsEmpty) {
    alertsEmpty.innerHTML =
      `${t("alerts_empty_1")} <span class="mono">/webhook/eset</span> ${t("alerts_empty_2")}`;
  }
}

function updateLangButtons() {
  const ja = document.getElementById("langBtnJa");
  const en = document.getElementById("langBtnEn");
  if (!ja || !en) return;
  const isJa = state_lang.current === "ja";
  ja.className = "small" + (isJa ? " primary" : "");
  en.className = "small" + (isJa ? "" : " primary");
  // The style change alone conveys nothing to assistive tech; the theme pair
  // already carries aria-pressed, and this mirrors it.
  ja.setAttribute("aria-pressed", String(isJa));
  en.setAttribute("aria-pressed", String(!isJa));
}

/** Switches the dashboard language and re-renders everything currently on screen
 * from already-cached state — except the Emails section, which is intentionally
 * skipped so its content never changes with the language toggle. */
function setLang(lang) {
  if (lang !== "ja" && lang !== "en") return;
  state_lang.current = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) { /* storage blocked — the choice still applies to this page view */ }
  // Keeps the document's declared language in step with the UI's. A screen
  // reader picks its voice from this attribute, and the browser picks Japanese
  // line-breaking and font fallback from it — with a hard-coded lang="en" the
  // Japanese dashboard was announced by an English voice throughout.
  document.documentElement.lang = lang;
  updateLangButtons();
  applyStaticI18n();
  // #wsLabel deliberately carries no data-i18n (applyStaticI18n would reset a
  // live connection's label to "connecting…"), so it is re-rendered from its own
  // state here instead.
  if (typeof renderWsStatus === "function") renderWsStatus();
  if (typeof refreshCurrentViewTranslations === "function") refreshCurrentViewTranslations();
}

document.addEventListener("DOMContentLoaded", () => {
  const jaBtn = document.getElementById("langBtnJa");
  const enBtn = document.getElementById("langBtnEn");
  if (jaBtn) jaBtn.onclick = () => setLang("ja");
  if (enBtn) enBtn.onclick = () => setLang("en");
  // The stored language is applied on load, so <html lang> has to be stamped on
  // load too — not only when the toggle is clicked.
  document.documentElement.lang = state_lang.current;
  updateLangButtons();
  applyStaticI18n();
});
